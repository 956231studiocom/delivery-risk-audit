#!/usr/bin/env python3
"""GitHub Action entrypoint: run the seven checks, publish the scorecard.

Reads Action inputs from the environment (INPUT_*), writes:
  - GITHUB_STEP_SUMMARY  -> the scorecard, visible on the run page
  - GITHUB_OUTPUT        -> score, grade, report path
  - the Markdown report  -> audit-report.md (artifact-friendly)

Exit code is 0 unless --fail-under is set and the score is below it.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audit  # noqa: E402


def env(name, default=""):
    v = os.environ.get(name)
    return default if v is None or v == "" else v


def append(path, text):
    if not path:
        return
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")


def set_output(key, value):
    append(os.environ.get("GITHUB_OUTPUT"), "%s=%s" % (key, value))


def main():
    target = env("INPUT_PATH", ".")
    name = env("INPUT_NAME") or None
    fail_under = env("INPUT_FAIL_UNDER")
    write_md = env("INPUT_MARKDOWN", "true").lower() in ("1", "true", "yes")
    report_path = env("INPUT_REPORT_PATH", "audit-report.md")

    if not os.path.isdir(target):
        print("::error::not a directory: %s" % target)
        return 2

    r = audit.run(target, name)
    score = r["total_score"]
    grade = r["risk_level"]
    md = audit.to_markdown(r)

    if write_md:
        with open(report_path, "w", encoding="utf-8") as fh:
            fh.write(md)
        print("report written: %s" % report_path)

    with open("audit-report.json", "w", encoding="utf-8") as fh:
        json.dump(r, fh, ensure_ascii=False, indent=2)

    # The run page is the shop window: score first, then the seven rows.
    published = md.replace(
        "*Generated by seven static checks.",
        "*Generated by [AI Delivery Risk Audit](https://956231studio.com/ai-code-audit/)."
        " Seven static checks.",
    )
    append(os.environ.get("GITHUB_STEP_SUMMARY"), published)

    set_output("score", score)
    set_output("grade", grade)
    set_output("report", report_path)
    set_output("json", "audit-report.json")

    print("%s: %s/100 (%s)" % (r["target"]["name"], score, grade))
    for c in r["checks"]:
        print("  %s %-12s %2d/10" % (c["id"], c["name"], c["score"]))

    if fail_under:
        try:
            floor = float(fail_under)
        except ValueError:
            print("::warning::fail-under is not a number: %s" % fail_under)
            floor = None
        if floor is not None and score < floor:
            print("::error::score %s is below fail-under %s" % (score, floor))
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
